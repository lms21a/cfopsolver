"""Bundle verbatim license files from the complete locked Cargo dependency graph."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_DEPENDENCIES.txt"


def generate() -> str:
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--locked", "--all-features", "--format-version", "1"],
            cwd=ROOT,
            text=True,
        )
    )
    groups: dict[str, list[str]] = {}
    for package in sorted(metadata["packages"], key=lambda item: (item["name"], item["version"])):
        if package["source"] is None:
            continue
        directory = Path(package["manifest_path"]).parent
        files = sorted(
            path
            for path in directory.iterdir()
            if path.is_file() and re.match(r"(?i)^(licen[cs]e|copying)(?:$|[-_.])", path.name)
        )
        if not files:
            raise RuntimeError(f"Missing license files for {package['name']} {package['version']}")
        for path in files:
            content = path.read_text(encoding="utf-8").strip()
            label = f"{package['name']} {package['version']} / {path.name} ({package['license']})"
            groups.setdefault(content, []).append(label)
    sections = [
        "Cargo dependency license notices\n"
        "Generated by scripts/generate_dependency_licenses.py from Cargo.lock.\n"
        "Includes optional, build, development, and target-specific dependencies.\n"
        "Identical license texts are grouped; original copyright notices are retained.\n"
    ]
    for content, labels in groups.items():
        sections.append("\n" + "=" * 78 + "\n" + "\n".join(labels) + "\n\n" + content + "\n")
    return "".join(sections)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    content = generate()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit(
                "Dependency notices are stale; run scripts/generate_dependency_licenses.py"
            )
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print("Dependency license notices are current.")


if __name__ == "__main__":
    main()
